export const similarVehicles = (vehicle: Vehicle, limit = 3) =>
  vehicles
    .filter((v) => v.id !== vehicle.id)
    .sort((a, b) => {
      const score = (v: Vehicle) =>
        (v.bodyType === vehicle.bodyType ? -2 : 0) + Math.abs(v.price - vehicle.price) / 1_000_000;
      return score(a) - score(b);
    })
    .slice(0, limit);

